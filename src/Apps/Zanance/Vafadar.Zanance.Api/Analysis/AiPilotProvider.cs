    /// <summary>Reads a signed-notice candidate from the configured dedicated project.</summary>
    internal async Task<JsonDocument?> RetrieveNoticeAsync(string provider, string id, CancellationToken ct)
    {
        if (!ValidId(id) || provider == "openai" && !id.StartsWith("resp_", StringComparison.Ordinal) ||
            Profile(AiPurpose.PeriodExplanation, provider, provider == "openai" ? "gpt-6-luna" : "gemini-3.5-flash-lite") is not { } profile)
            return null;
        var suffix = provider == "gemini" ? "?include_input=true" : "";
        using var request = Request(profile, HttpMethod.Get, profile.Url + "/" + id + suffix);
        return await SendAsync(request, ct);
    }

    /// <summary>Extracts the immutable operation from authenticated metadata or the exact stored user input.</summary>
    internal static string? RecoveredOperation(string provider, JsonElement response, string id)
    {
        if (Text(response, "id") != id || Text(response, "status") != "completed") return null;
        if (provider == "openai") return Text(Read(response, "metadata"), "zanance_operation");
        var input = Array(response, "steps").Where(item => Text(item, "type") == "user_input").Take(2).ToArray();
        if (input.Length != 1 || Text(input[0], "status") != "done") return null;
        var content = Array(input[0], "content").Take(2).ToArray();
        if (content.Length != 1 || Text(content[0], "type") != "text" || Text(content[0], "text") is not { } text) return null;
        var index = text.LastIndexOf(GeminiOperationPrefix, StringComparison.Ordinal);
        if (index < 0) return null;
        var operation = text[(index + GeminiOperationPrefix.Length)..];
        return operation.Length == 64 && operation.All(char.IsAsciiHexDigitLower) ? operation : null;
    }

    /// <summary>Revalidates model, route and content before consulting the original settlement policy.</summary>
    internal AiProviderOutcome? RecoveredNoticeOutcome(AiPilotRouteRow route, AiOffer offer, string digest, JsonElement response)
    {
        if (Admit(route, offer) is not { } profile || !IsSynthetic(offer.Purpose, digest) ||
            Text(response, "model") != profile.Model) return null;
        return Outcome(profile, offer.Purpose, digest, response);
    }

    /// <summary>Checks the original preserved route and known synthetic payload before reserving an operator lookup.</summary>
    internal bool CanCheckStatus(AiPilotRouteRow route, AiOffer offer, string digest, string id) =>
        ValidId(id) && Admit(route, offer) is not null && IsSynthetic(offer.Purpose, digest);

    /// <summary>Reads only the saved original execution and its matching vendor project.</summary>
    internal async Task<AiProviderOutcome> StatusAsync(AiPilotRouteRow route, AiOffer offer, string digest, string? id, CancellationToken ct)
    {
        if (!ValidId(id) || Admit(route, offer) is not { } profile || !IsSynthetic(offer.Purpose, digest)) return Unknown;
        using var request = Request(profile, HttpMethod.Get, profile.Url + "/" + id);
        using var result = await SendAsync(request, ct);
        return result is not null && Text(result.RootElement, "id") == id ? Outcome(profile, offer.Purpose, digest, result.RootElement) : Unknown;
    }

    private async Task<JsonDocument?> SendAsync(HttpRequestMessage request, CancellationToken ct)
    {
        using var client = clients.CreateClient(Client);
        using var response = await client.SendAsync(request, ct);
        if (!response.IsSuccessStatusCode) return null;
        try { return await JsonDocument.ParseAsync(await response.Content.ReadAsStreamAsync(ct), cancellationToken: ct); }
        catch (JsonException) { return null; }
    }

    private static AiProviderOutcome Outcome(PilotProfile profile, AiPurpose purpose, string digest, JsonElement response)
    {
        var status = Text(response, "status");
        if (status is not ("completed" or "failed" or "incomplete" or "cancelled") || Text(response, "model") != profile.Model) return Unknown;
        var usage = Read(response, "usage");
        var openAi = profile.Provider == "openai";
        var input = Number(usage, openAi ? "input_tokens" : "total_input_tokens");
        var output = Number(usage, openAi ? "output_tokens" : "total_output_tokens");
        var thinking = openAi ? Number(Read(usage, "output_tokens_details"), "reasoning_tokens") : Number(usage, "total_thought_tokens");
        var cached = openAi ? Number(Read(usage, "input_tokens_details"), "cached_tokens") : Number(usage, "total_cached_tokens");
        if (input is not (>= 0 and <= 1_000_000) || output is not (>= 0 and <= 1_000_000) ||
            !openAi && thinking is < 0 or > 1_000_000) return Unknown;
        var totalOutput = output.Value + (openAi ? 0 : thinking ?? 0);
        var metering = new AiPilotUsage(input.Value, totalOutput, InRange(cached, input.Value), InRange(thinking, totalOutput),
            StandardEstimate(profile.Model, input.Value, totalOutput));
        var unpublished = Unknown with { Metering = metering };
        if (status != "completed" || input is < 1 or > InputTokenLimit || totalOutput > profile.OutputLimit || output is < 1)
            return unpublished;

        static int? InRange(int? count, int total) => count >= 0 && count <= total ? count : null;
        var values = Array(response, openAi ? "output" : "steps")
            .Where(item => Text(item, "type") == (openAi ? "message" : "model_output"))
            .SelectMany(item => Array(item, "content"))
            .Where(item => Text(item, "type") == (openAi ? "output_text" : "text"))
            .Select(item => Text(item, "text")).ToArray();
        if (values.Length != 1 || values[0] is not { } value) return unpublished;
        try
        {
            using var parsed = JsonDocument.Parse(value);
            var root = parsed.RootElement;
            var expected = Expected(purpose, digest);
            if (root.ValueKind != JsonValueKind.Object || root.EnumerateObject().Count() != expected.Count + 1 ||
                !expected.All(pair => pair.Value is int number ? Number(root, pair.Key) == number
                    : Read(root, pair.Key).ValueKind == JsonValueKind.False) ||
                Text(root, "explanation") is not { } explanation) return unpublished;
            if (FundingByDigest.TryGetValue(digest, out var funding) && funding.Kind != AiFundingKind.BudgetLimit &&
                explanation.Any(char.IsDigit)) return unpublished;
            if ((digest == ForecastDigest || digest == ForecastBaselineDigest || digest == SpendingQuestionDigest || digest == PlanQuestionDigest) && explanation.Any(char.IsDigit)) return unpublished;
            AiProtocol.ValidateText(explanation);
            return new(AiProviderState.Completed, 1, explanation, metering);
        }
        catch (Exception error) when (error is JsonException or ArgumentException) { return unpublished; }
    }

    private static long StandardEstimate(string model, int input, int output)
    {
        // Published Standard text rates on 2026-11-19 in nano-USD per token; no cache discount is assumed.
        var (inputRate, outputRate) = model switch
        {
            "gpt-6-luna" => (100L, 500L),
            "gemini-3.5-flash-lite" => (300L, 2500L),
            "gpt-6.2-sol" => (2000L, 10000L),
            "gemini-4-hydrogen" => (1500L, 7500L),
            _ => throw new InvalidOperationException("The model has no approved pilot tariff."),
        };
        return (input * inputRate + output * outputRate + 999) / 1000;
    }

    private PilotProfile? Admit(AiPilotRouteRow route, AiOffer offer)
    {
        var profile = Profile(route.Purpose, route.Provider, route.Model);
        return profile is not null && profile.Revision == route.Revision && profile.Provider == offer.Provider
            && profile.Model == offer.Model && offer.Purpose == route.Purpose ? profile : null;
    }

    private static string FundingTask(AiFundingFacts facts)
    {
        var task = facts.Kind switch
        {
            AiFundingKind.BudgetLimit => FormattableString.Invariant(
                $"Base limit {facts.Existing}, carry {facts.Carry}, effective limit {facts.Baseline}, and net spending {facts.Observed}. Explain the over-limit amount and the alternative base limit that would match recorded spending if carry stayed the same. Compare with keeping the current base limit."),
            AiFundingKind.BudgetSuggestion => FormattableString.Invariant(
                $"Average net spending {facts.Observed} over {facts.PeriodCount} completed periods. The locally rounded suggestion is {facts.Baseline} and the saved limit is {facts.Existing}. Explain the rounding difference and compare keeping the original saved limit with reviewing the rounded suggestion."),
            _ => FormattableString.Invariant(
                $"Target {facts.Baseline}, funded {facts.Observed}, uncovered earmarks {facts.Unfunded}. There are {facts.PeriodCount} contribution dates. The saved plan is {facts.PlannedContribution} each and the engine's alternative is {facts.RequiredContribution} each. Explain the remaining amount and compare both scenarios without promising funding."),
        };
        const string prefix = "Synthetic Zanance example, EUR minor units. ";
        if (facts.Kind == AiFundingKind.BudgetLimit)
            return prefix + task + " Return difference_minor (over-limit amount), alternative_minor and a brief English explanation. State facts only. Never direct a payment or claim the draft was saved.";
        return prefix + task + FormattableString.Invariant(
            $" Copy the exact precomputed integer difference_minor={facts.Difference} and alternative_minor={facts.Alternative()} to those JSON fields. Never convert or scale the integers. Explain only how the figures relate, in brief English prose without digits, spelled-out amounts, advice or a claim that edits were saved. The app displays the exact numeric figures beside your explanation.");
    }

    private static Dictionary<string, object> Expected(AiPurpose purpose, string digest)
    {
        if (FundingByDigest.TryGetValue(digest, out var funding))
            return new() { ["difference_minor"] = (int)funding.Difference, ["alternative_minor"] = (int)funding.Alternative()!.Value };
        if (digest == SpendingQuestionDigest) return new() { ["spending_change_minor"] = 13000, ["contributing_rows"] = 1 };
        if (digest == PlanQuestionDigest) return new() { ["first_day"] = 4, ["earlier_unknown_count"] = 1 };
        if (digest == ForecastBaselineDigest) return new() { ["first_day"] = 5, ["minimum_day"] = 10, ["unknown_count"] = 1 };
        if (digest == ForecastDigest) return new() { ["baseline_first_day"] = 5, ["scenario_first_day"] = 0, ["unknown_count"] = 1 };
        if (digest == CategoryDigest) return new() { ["largest_increase"] = 1, ["largest_decrease"] = 2 };
        if (digest == PlanDigest)
            return new() { ["largest_overrun"] = 1, ["largest_underrun"] = 4, ["open_rows"] = 1, ["unknown_rows"] = 1 };
        return purpose == AiPurpose.PeriodComparison
            ? new() { ["eur_spending_change"] = -6000, ["usd_spending_change"] = 5000,
                ["eur_cash_flow_change"] = 7000, ["usd_cash_flow_change"] = -3000, ["can_combine"] = false }
            : new() { ["net_expenses_minor"] = 38000 };
    }

    private PilotProfile? Profile(AiPurpose purpose, string provider, string? selectedModel)
    {
        if (provider is not ("openai" or "gemini")) return null;
        if (selectedModel is null ? purpose != AiPurpose.PeriodExplanation
            : !Models(purpose).Contains(selectedModel, StringComparer.Ordinal) || ModelProvider(selectedModel) != provider) return null;
        var settings = configuration.GetSection("Analysis:ProviderPilot");
        var key = settings[$"{provider}:ApiKey"];
        var project = settings[$"{provider}:Project"];
        if (string.IsNullOrWhiteSpace(key) || !ValidId(project)) return null;
        var openAi = provider == "openai";
        var comparison = purpose == AiPurpose.PeriodComparison;
        var model = selectedModel ?? (openAi ? "gpt-6.2-sol" : "gemini-4-hydrogen");
        var reasoning = comparison ? "medium" : "low";
        // Hydrogen bills thinking against the same limit. The 1024-token trial exhausted it before emitting JSON.
        var outputLimit = comparison ? (openAi ? 1024 : 4096) : 512;
        var sendHeader = settings.GetValue("openai:SendProjectHeader", true);
        var revisionInput = selectedModel is null && (!openAi || sendHeader)
            ? $"zanance-pilot-v1|{provider}|{model}|{project}"
            : $"zanance-pilot-v2|{purpose}|{provider}|{model}|{project}|{reasoning}|{outputLimit}|{openAi && sendHeader}";
        var revision = Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(revisionInput)));
        return new(provider, model, revision, openAi && sendHeader ? project : null, key, reasoning, outputLimit, openAi
            ? "https://api.openai.com/v1/responses" : "https://generativelanguage.googleapis.com/v1beta/interactions");
    }

    private static string ModelProvider(string model) => model.StartsWith("gpt-", StringComparison.Ordinal) ? "openai" : "gemini";

    private static HttpRequestMessage Request(PilotProfile profile, HttpMethod method, string url)
    {
        var request = new HttpRequestMessage(method, url);
        if (profile.Provider == "openai")
        {
            request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", profile.Key);
            if (profile.ProjectHeader is { } project) request.Headers.Add("OpenAI-Project", project);
        }
        else
        {
            request.Headers.Add("x-goog-api-key", profile.Key);
            request.Headers.Add("Api-Revision", "2026-05-20");
        }
        return request;
    }

    private static bool ValidId(string? value) => value is { Length: > 0 and <= 250 }
        && value.All(c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_');
    private static JsonElement Read(JsonElement value, string name) => value.ValueKind == JsonValueKind.Object
        && value.TryGetProperty(name, out var found) ? found : default;
    private static string? Text(JsonElement value, string name) => Read(value, name) is { ValueKind: JsonValueKind.String } found
        ? found.GetString() : null;
    private static int? Number(JsonElement value, string name) => Read(value, name) is { ValueKind: JsonValueKind.Number } found
        && found.TryGetInt32(out var number) ? number : null;
    private static IEnumerable<JsonElement> Array(JsonElement value, string name) =>
        Read(value, name) is { ValueKind: JsonValueKind.Array } found ? found.EnumerateArray() : [];
    private sealed record PilotProfile(string Provider, string Model, string Revision, string? ProjectHeader, string Key,
        string Reasoning, int OutputLimit, string Url);
