    /// <summary>Preserves the original operator command for the legacy report profile.</summary>
    internal Task SelectAsync(ServiceDbContext db, string provider, string actor, CancellationToken ct)
        => SaveSelectionAsync(db, AiPurpose.PeriodExplanation, provider, null, actor, ct);

    /// <summary>Selects an allowlisted model or disables just the selected purpose.</summary>
    internal Task SelectModelAsync(ServiceDbContext db, AiPurpose purpose, string model, string actor, CancellationToken ct,
        long? expectedRouteId = null)
    {
        var models = Models(purpose);
        if (models.Length == 0 || (model != "off" && !models.Contains(model, StringComparer.Ordinal)))
            throw new InvalidOperationException("Analysis pilot model is not allowed for this purpose.");
        return SaveSelectionAsync(db, purpose, model == "off" ? "off" : ModelProvider(model),
            model == "off" ? null : model, actor, ct, expectedRouteId);
    }

    private async Task SaveSelectionAsync(ServiceDbContext db, AiPurpose purpose, string provider, string? model, string actor,
        CancellationToken ct, long? expectedRouteId = null)
    {
        if (actor.Length is < 1 or > 256) throw new InvalidOperationException("Invalid analysis pilot operator.");
        var profile = Profile(purpose, provider, model);
        if (provider != "off" && profile is null) throw new InvalidOperationException("Analysis pilot provider is unavailable.");
        await using var transaction = await db.Database.BeginTransactionAsync(ct);
        await LockAsync(db, ct);
        if (expectedRouteId is { } expected && ((await LatestAsync(db, purpose, ct))?.Id ?? 0) != expected)
            throw new AiRefusal(409, "AiPilotSelectionChanged");
        db.Add(new AiPilotRouteRow { Purpose = purpose, Provider = provider, Model = model, Revision = profile?.Revision ?? "",
            Actor = actor, SelectedAt = time.GetUtcNow() });
        await db.SaveChangesAsync(ct);
        await transaction.CommitAsync(ct);
    }

    /// <summary>Reads the current default and quote terms without egress.</summary>
    internal async Task<(AiProviderOffer Offer, long RouteId)?> OfferAsync(ServiceDbContext db, AiPurpose purpose, CancellationToken ct)
    {
        var selected = await LatestAsync(db, purpose, ct);
        var profile = selected is null ? null : Profile(purpose, selected.Provider, selected.Model);
        return profile is not null && selected!.Revision == profile.Revision
            ? (new(profile.Provider, profile.Model, 1), selected.Id) : null;
    }

    /// <summary>Returns the recorded choice and readiness even if its provider credentials have become unavailable.</summary>
    internal async Task<(string Model, long RouteId, bool Available)> SelectionAsync(ServiceDbContext db, AiPurpose purpose, CancellationToken ct)
    {
        var selected = await LatestAsync(db, purpose, ct);
        if (selected is null || selected.Provider == "off") return ("off", selected?.Id ?? 0, true);
        var model = selected.Model ?? (selected.Provider == "openai" ? "gpt-6.2-sol" : "gemini-4-hydrogen");
        return (model, selected.Id, Profile(purpose, selected.Provider, selected.Model)?.Revision == selected.Revision);
    }

    private static Task<AiPilotRouteRow?> LatestAsync(ServiceDbContext db, AiPurpose purpose, CancellationToken ct) =>
        db.Set<AiPilotRouteRow>().AsNoTracking().Where(r => r.Purpose == purpose).OrderByDescending(r => r.Id).FirstOrDefaultAsync(ct);

    /// <summary>Limits the fixed request and output to twenty accepted attempts per provider per pilot store.</summary>
    internal Task<bool> AtCapacityAsync(ServiceDbContext db, string provider, CancellationToken ct)
        => db.Set<AiRequestRow>().Where(r => r.State != AiRequestState.NotAccepted)
            .Join(db.Set<AiOfferRow>().Where(o => o.PilotRouteId != null && o.Provider == provider),
                r => r.OfferId, o => o.Id, (r, o) => r.Id)
            .OrderBy(id => id).Skip(MaxAttemptsPerProvider - 1).AnyAsync(ct);

    /// <summary>Computes and admits the original uncached ceiling within the caller's pilot admission lock.</summary>
    internal async Task<long?> AvailableCostCeilingAsync(ServiceDbContext db, string owner, AiPilotRouteRow route, AiOffer offer, CancellationToken ct)
    {
        if (Admit(route, offer) is not { } profile) return null;
        var ceiling = StandardEstimate(profile.Model, InputTokenLimit, profile.OutputLimit);
        if (ceiling > BudgetLimit("Request", LegacyCostCeilingMicros)) return null;
        var previous = CommittedRequests(db);

        // Count retained ceilings even on completion, because vendor invoices are not reconciled here.
        var userCommitted = await previous.Where(item => item.UserId == owner).SumAsync(item => item.Cost, ct);
        if (userCommitted > BudgetLimit("User", 4 * LegacyCostCeilingMicros) - ceiling) return null;
        // Provider-wide accounting also carries prior project revisions, so rotation cannot replenish the budget.
        var projectCommitted = await previous.Where(item => item.Provider == profile.Provider).SumAsync(item => item.Cost, ct);
        return projectCommitted <= BudgetLimit("Project", MaxAttemptsPerProvider * LegacyCostCeilingMicros) - ceiling
            ? ceiling : null;
    }

    private static IQueryable<CommittedRequest> CommittedRequests(ServiceDbContext db) =>
        from request in db.Set<AiRequestRow>()
        join offer in db.Set<AiOfferRow>().Where(item => item.PilotRouteId != null)
            on request.OfferId equals offer.Id
        where request.State != AiRequestState.NotAccepted
        select new CommittedRequest
        {
            UserId = request.UserId, Provider = offer.Provider, State = request.State, Stage = request.PilotDispatchStage,
            HasHandle = request.VendorOperationId != null, Cost = request.PilotCostCeilingMicros ?? LegacyCostCeilingMicros,
            Estimate = request.PilotMeteredCostMicros,
        };

    private sealed class CommittedRequest
    {
        public required string UserId { get; init; }
        public required string Provider { get; init; }
        public AiRequestState State { get; init; }
        public AiPilotDispatchStage? Stage { get; init; }
        public bool HasHandle { get; init; }
        public long Cost { get; init; }
        public long? Estimate { get; init; }
    }


    /// <summary>Reports aggregate receipt, budget and dispatch health from the original admitted requests.</summary>
    internal static Task<List<PilotOperations>> OperationsAsync(ServiceDbContext db, CancellationToken ct) =>
        CommittedRequests(db).GroupBy(item => item.Provider).Select(group => new PilotOperations(group.Key, group.Count(),
            group.Sum(item => item.Cost), group.Count(item => item.Estimate != null), group.Sum(item => item.Estimate),
            group.Count(item => item.State == AiRequestState.Pending && !item.HasHandle && item.Stage == AiPilotDispatchStage.Queued),
            group.Count(item => item.State == AiRequestState.Pending && item.HasHandle),
            group.Count(item => item.State == AiRequestState.Pending && !item.HasHandle && item.Stage != AiPilotDispatchStage.Queued)))
            .ToListAsync(ct);

    /// <summary>Aggregate reconciliation evidence without request, customer or vendor operation identifiers.</summary>
    internal sealed record PilotOperations(string Provider, int Accepted, long Committed, int Metered, long? Estimate,
        int Queued, int PendingWithHandle, int PendingWithoutHandle);

    /// <summary>Current synthetic budget settings. Invalid values leave admission closed.</summary>
    internal (long? Request, long? User, long? Project) ReadBudgetLimits() =>
        (ConfiguredBudget("Request", LegacyCostCeilingMicros), ConfiguredBudget("User", 4 * LegacyCostCeilingMicros),
            ConfiguredBudget("Project", MaxAttemptsPerProvider * LegacyCostCeilingMicros));

    private long BudgetLimit(string scope, long maximum) => ConfiguredBudget(scope, maximum)
        ?? throw new InvalidOperationException("The configured synthetic pilot budget is outside its approved bound.");

    private long? ConfiguredBudget(string scope, long maximum)
    {
        var literal = configuration[$"Analysis:ProviderPilot:Budget:{scope}Micros"];
        if (literal is null) return maximum;
        return long.TryParse(literal, NumberStyles.Integer, CultureInfo.InvariantCulture, out var value) && value >= 0 && value <= maximum
            ? value : null;
    }

